export function editorText(language: SiteLanguage, text: string): string {
  if (language === 'en') {
    const exactTranslation = translations[text];
    if (exactTranslation) return exactTranslation;
    const moveMatch = text.match(/^Pindahkan (.+) ke (kiri|kanan)$/);
    if (moveMatch) return `Move ${moveMatch[1]} ${moveMatch[2] === 'kiri' ? 'left' : 'right'}`;
    const deleteMatch = text.match(/^Hapus (.+)$/);
    if (deleteMatch) return `Delete ${deleteMatch[1]}`;
    return text;
  }
  return text;
}

export function useEditorText() {
  const { language } = useLanguage();
  return (text: string) => editorText(language, text);
}